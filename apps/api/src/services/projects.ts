import { buildColoringDocument, ColoringInteriorSettings, defaultSpecSource, InteriorDocument, MetadataDraft, type InteriorDocumentInput, type PageInstanceInput } from '@kdp/core';
import type { Prisma, Project, ProjectStatus } from '@prisma/client';
import type { z } from 'zod';
import { prisma } from '../db';
import { badRequest, notFound } from '../lib/errors';
import { DEFAULT_CONTENT_CLASS, type ContentType, type CreateProjectInput } from './schemas';
import { saveDocument } from './interior';

export const STATUS_ORDER: ProjectStatus[] = ['DRAFT', 'RESEARCH', 'CONTENT', 'INTERIOR', 'COVER', 'VALIDATION', 'READY_FOR_REVIEW', 'EXPORTED'];

/** Every project read goes through this so cross-workspace access is impossible. */
export async function getProject(workspaceId: string, id: string): Promise<Project> {
  const p = await prisma.project.findFirst({ where: { id, workspaceId, archivedAt: null } });
  if (!p) throw notFound('Project');
  return p;
}

/** Moves status forward only (generation stages); manual changes use setStatus. */
export async function advanceStatus(projectId: string, to: ProjectStatus) {
  const p = await prisma.project.findUniqueOrThrow({ where: { id: projectId } });
  if (STATUS_ORDER.indexOf(to) > STATUS_ORDER.indexOf(p.status)) await prisma.project.update({ where: { id: projectId }, data: { status: to } });
}

export async function setStatus(project: Project, to: ProjectStatus) {
  if (to === 'EXPORTED') throw badRequest('EXPORTED is set automatically when an export bundle is created.');
  if (to === 'READY_FOR_REVIEW') {
    const latest = await prisma.validationReport.findFirst({ where: { projectId: project.id }, orderBy: { createdAt: 'desc' } });
    if (!latest || latest.blocked) throw badRequest('A validation report without blocking failures is required before Ready for Review.');
  }
  return prisma.project.update({ where: { id: project.id }, data: { status: to } });
}

const p = (id: string, templateId: string, fields: Record<string, string | number | boolean> = {}): PageInstanceInput => ({ id, templateId, fields });

/** Starter interior for each content type — editable immediately, regenerated by AI if requested. */
export function starterDocument(contentType: z.infer<typeof ContentType>, title: string, author: string, pages: number): InteriorDocumentInput {
  const front: PageInstanceInput[] = [p('title', 'title-page'), p('copyright', 'copyright-page', { year: String(new Date().getUTCFullYear()) })];
  const n = Math.max(1, pages - front.length);
  const repeat = (tpl: string) => Array.from({ length: n }, (_, i) => p(`p${i + 1}`, tpl));
  const settings = { title, author };
  switch (contentType) {
    case 'BLANK':
      return { settings: { ...settings, pageNumbers: { enabled: false } }, frontMatter: front, body: { kind: 'pages', pages: Array.from({ length: n }, (_, i) => ({ id: `p${i + 1}`, templateId: null, elements: [] })) } };
    case 'LINED':
      return { settings, frontMatter: [...front, p('belongs', 'belongs-to')], body: { kind: 'pages', pages: repeat('lined-journal').slice(1) } };
    case 'DOT_GRID':
      return { settings, frontMatter: front, body: { kind: 'pages', pages: repeat('dot-grid') } };
    case 'PLANNER':
      return { settings, frontMatter: [...front, p('howto', 'how-to-use')], body: { kind: 'pages', pages: Array.from({ length: n - 1 }, (_, i) => p(`p${i + 1}`, i % 8 === 0 ? 'weekly-planner' : 'daily-planner')) } };
    case 'LOGBOOK':
    case 'STRUCTURED_FORMS':
      return { settings, frontMatter: [...front, p('howto', 'how-to-use')], body: { kind: 'pages', pages: Array.from({ length: n - 1 }, (_, i) => p(`p${i + 1}`, i % 4 === 3 ? 'equipment-inspection' : 'work-order-log')) } };
    case 'WORKBOOK':
      return { settings, frontMatter: [...front, p('howto', 'how-to-use'), p('toc', 'toc')], body: { kind: 'pages', pages: Array.from({ length: n - 2 }, (_, i) => p(`p${i + 1}`, i % 6 === 0 ? 'chapter-page' : 'workbook-exercise', i % 6 === 0 ? { chapterLabel: `Part ${i / 6 + 1}`, chapterTitle: `Part ${i / 6 + 1}` } : {})) } };
    case 'COLORING':
      // Body is built from approved coloring pages in the Coloring Studio.
      return buildColoringDocument([], ColoringInteriorSettings.parse({}), { title, author });
    case 'ILLUSTRATED':
      return { settings, frontMatter: front, body: { kind: 'pages', pages: Array.from({ length: n }, (_, i) => ({ id: `p${i + 1}`, templateId: null, elements: [{ id: 'text', type: 'text', text: '', style: { align: 'center', sizePt: 18 } }] })) } };
    case 'LONG_FORM':
      return { settings: { ...settings, runningHeader: { enabled: true } }, frontMatter: [...front, p('toc', 'toc')], body: { kind: 'flow', chapters: [{ id: 'c1', title: 'Chapter One', blocks: [{ type: 'paragraph', text: '' }], notes: [] }] } };
  }
}

export async function createProject(workspaceId: string, userId: string, input: z.infer<typeof CreateProjectInput>) {
  const { brief, format, generation } = input;
  const lib = defaultSpecSource.getLibrary();
  if (format.format !== 'EBOOK') {
    const trim = lib.trimSizes.find((t) => t.id === format.trimId);
    if (!trim) throw badRequest(`Unknown trim size ${format.trimId}`);
    if (!trim.formats.includes(format.format)) throw badRequest(`Trim ${trim.label} is not available for ${format.format.toLowerCase()}`);
  }
  const contentClass = brief.contentClass ?? DEFAULT_CONTENT_CLASS[brief.category];
  const target = format.targetPageCount ?? (format.format === 'HARDCOVER' ? 120 : 100);
  const doc = InteriorDocument.parse(starterDocument(brief.contentType, brief.workingTitle, brief.authorName, target));
  const metadata = MetadataDraft.parse({ title: brief.workingTitle, author: brief.authorName, language: brief.language, lowContent: contentClass === 'LOW' });

  const project = await prisma.$transaction(async (tx) => {
    const project = await tx.project.create({
      data: {
        workspaceId,
        title: brief.workingTitle,
        category: brief.category,
        contentClass,
        createdById: userId,
        brief: {
          create: {
            workingTitle: brief.workingTitle,
            targetReader: brief.targetReader,
            readerProblem: brief.readerProblem,
            niche: brief.niche,
            differentiation: brief.differentiation,
            language: brief.language,
            marketplace: brief.marketplace,
            authorName: brief.authorName,
            contentStyle: brief.contentStyle,
            designTheme: brief.designTheme,
            contentType: brief.contentType,
            generationSettings: generation,
          },
        },
        format: {
          create: {
            format: format.format,
            trimId: format.trimId,
            ink: format.ink,
            paper: format.paper,
            bleed: format.bleed,
            coverFinish: format.coverFinish,
            direction: format.direction,
            targetPageCount: format.targetPageCount,
            specVersion: lib.version,
          },
        },
        metadataDrafts: { create: { data: metadata as unknown as Prisma.InputJsonValue } },
      },
    });
    await tx.interiorDocument.create({ data: { projectId: project.id, settings: doc.settings as unknown as Prisma.InputJsonValue, bodyKind: doc.body.kind } });
    return project;
  });
  await saveDocument(project.id, doc, null);
  return project;
}

export async function projectSummary(workspaceId: string, id: string) {
  const project = await prisma.project.findFirst({
    where: { id, workspaceId, archivedAt: null },
    include: { brief: true, format: true, batchItem: { select: { id: true, status: true, batchId: true } } },
  });
  if (!project) throw notFound('Project');
  const [latestReport, jobs, metadata, exports] = await Promise.all([
    prisma.validationReport.findFirst({ where: { projectId: id }, orderBy: { createdAt: 'desc' }, select: { id: true, blocked: true, summary: true, createdAt: true, projectVersion: true } }),
    prisma.generationJob.findMany({ where: { projectId: id }, orderBy: { createdAt: 'desc' }, take: 5, select: { id: true, type: true, status: true, stage: true, progress: true, createdAt: true, error: true } }),
    prisma.metadataDraft.findFirst({ where: { projectId: id, isCurrent: true } }),
    prisma.exportArtifact.count({ where: { projectId: id } }),
  ]);
  return { ...project, latestReport, jobs, metadata: metadata?.data ?? null, exportCount: exports };
}
